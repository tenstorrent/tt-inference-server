"""Grade generated video clips with a vision LLM.

The model sees what a person reviewing the clip would: the conditioning image,
the prompt and frames sampled across the clip, and scores it against a fixed
rubric. It catches what CLIP cannot, such as a subject that morphs, an
implausible setting or a washed-out ending. Informational: nothing gates on it,
since an LLM's scores move between calls.

Runs as its own CI step after the tests, over the clips the video eval saved
(``<run output>/videos/evals/index.json``), through the TT chat gateway the
CI AI summaries use (``TT_CHAT_API_KEY``, ``TT_CHAT_URL``, ``TT_CHAT_MODEL``):

    python -m test_module._test_common.video_llm_judge --videos-dir <dir>
"""

from __future__ import annotations

import argparse
import base64
import io
import json
import logging
import os
import statistics
import sys
from pathlib import Path
from typing import Any

import requests

from .vbench_i2v import find_conditioning_image

logger = logging.getLogger(__name__)

DEFAULT_MODEL = "anthropic/claude-sonnet-4-6"
NUM_FRAMES = 9
FRAME_WIDTH = 512
REQUEST_TIMEOUT_SECONDS = 300
CRITERIA = {
    "conditioning_fidelity": (
        "Frame 0 matches the conditioning image, and later frames stay recognisably "
        "the same place and subjects. Score 3 if there is no conditioning image."
    ),
    "prompt_adherence": "The clip shows what the prompt describes.",
    "temporal_coherence": (
        "Subjects keep their identity, shape and count across frames; no morphing, "
        "flicker or sudden jumps."
    ),
    "visual_quality": (
        "Sharp and well exposed, without artifacts such as blur, washout, smearing "
        "or distorted faces and hands."
    ),
    "motion_plausibility": (
        "There is real motion, and it is physically plausible for the scene."
    ),
}
INSTRUCTIONS = (
    "You are reviewing a short video generated by a text+image-to-video model. "
    "You get the prompt, the conditioning image it started from, and frames "
    "sampled evenly across the clip in order. Score each criterion from 1 "
    "(fails) to 5 (no problem):\n"
    + "\n".join(f"- {name}: {text}" for name, text in CRITERIA.items())
    + "\n\nReply with only a JSON object, no other text: "
    '{"scores": {"<criterion>": <1-5>, ...}, "issues": ["<short concrete '
    'problem>", ...], "summary": "<one sentence>"}. Use an empty issues list '
    "when there are none."
)


def gateway_url(base_url: str) -> str:
    """The gateway's /v1 chat route; its bare route sits behind a stricter WAF."""
    base = base_url.rstrip("/")
    if not base.endswith("/v1"):
        base += "/v1"
    return f"{base}/chat/completions"


def _jpeg_data_url(image, width: int = FRAME_WIDTH) -> str:
    """A PIL image, scaled to ``width``, as a base64 JPEG data URL."""
    height = max(1, round(image.height * width / image.width))
    buffer = io.BytesIO()
    image.convert("RGB").resize((width, height)).save(buffer, "JPEG", quality=85)
    return "data:image/jpeg;base64," + base64.b64encode(buffer.getvalue()).decode()


def sample_frames(video_path: Path, count: int = NUM_FRAMES) -> list[tuple[int, Any]]:
    """``count`` frames spread evenly from first to last, as (index, PIL image)."""
    import imageio.v3 as iio
    from PIL import Image

    frames = list(iio.imiter(video_path))
    last = len(frames) - 1
    indices = sorted({round(i * last / (count - 1)) for i in range(count)})
    return [(i, Image.fromarray(frames[i])) for i in indices]


def build_messages(
    prompt: str, frames: list[tuple[int, Any]], total_frames: int, image=None
) -> list[dict]:
    """One user message: rubric, prompt, conditioning image, then frames in order."""
    content: list[dict] = [
        {"type": "text", "text": INSTRUCTIONS},
        {"type": "text", "text": f"Prompt: {prompt}"},
    ]
    if image is not None:
        content += [
            {"type": "text", "text": "Conditioning image:"},
            {"type": "image_url", "image_url": {"url": _jpeg_data_url(image)}},
        ]
    else:
        content.append({"type": "text", "text": "No conditioning image."})
    for index, frame in frames:
        content += [
            {"type": "text", "text": f"Frame {index} of {total_frames}:"},
            {"type": "image_url", "image_url": {"url": _jpeg_data_url(frame)}},
        ]
    return [{"role": "user", "content": content}]


def parse_verdict(text: str) -> dict:
    """The model's JSON verdict, checked against the rubric."""
    start, end = text.find("{"), text.rfind("}")
    if start < 0 or end < start:
        raise ValueError(f"no JSON object in reply: {text[:200]!r}")
    verdict = json.loads(text[start : end + 1])
    scores = verdict.get("scores", {})
    missing = [name for name in CRITERIA if name not in scores]
    if missing:
        raise ValueError(f"reply is missing scores for {missing}")
    for name in CRITERIA:
        if not isinstance(scores[name], (int, float)) or not 1 <= scores[name] <= 5:
            raise ValueError(f"score for {name} is not 1-5: {scores[name]!r}")
    return {
        "scores": {name: scores[name] for name in CRITERIA},
        "overall": round(statistics.mean(scores[name] for name in CRITERIA), 2),
        "issues": [str(issue) for issue in verdict.get("issues", [])],
        "summary": str(verdict.get("summary", "")),
    }


def judge_clip(
    video_path: Path,
    prompt: str,
    *,
    api_key: str,
    base_url: str,
    model: str = DEFAULT_MODEL,
    image_path: Path | None = None,
) -> dict:
    """Ask the model for a verdict on one clip; raises on any failure."""
    from PIL import Image

    frames = sample_frames(video_path)
    total = frames[-1][0] + 1
    image = Image.open(image_path) if image_path else None
    response = requests.post(
        gateway_url(base_url),
        headers={"Authorization": f"Bearer {api_key}"},
        json={
            "model": model,
            "messages": build_messages(prompt, frames, total, image),
            "temperature": 0,
            "max_tokens": 1500,
        },
        timeout=REQUEST_TIMEOUT_SECONDS,
    )
    if response.status_code != 200:
        raise RuntimeError(
            f"gateway returned {response.status_code}: {response.text[:300]}"
        )
    choices = response.json().get("choices") or []
    if not choices:
        raise RuntimeError(f"gateway returned no choices: {response.text[:300]}")
    return parse_verdict(choices[0]["message"]["content"])


def judge_directory(
    videos_dir: Path,
    *,
    api_key: str,
    base_url: str,
    model: str = DEFAULT_MODEL,
    images_dir: Path | None = None,
) -> dict:
    """Judge every clip in a saved eval folder's index.json; one failure skips one clip.

    Conditioning images come from ``images_dir``, or else from whichever eval pair
    set in test_fixtures/datasets has them.
    """
    index = json.loads((videos_dir / "index.json").read_text())
    clips = []
    for entry in index:
        image_name = entry.get("conditioning_image")
        record = {
            "file": entry["file"],
            "prompt": entry["prompt"],
            "conditioning_image": image_name,
        }
        try:
            record.update(
                judge_clip(
                    videos_dir / entry["file"],
                    entry["prompt"],
                    api_key=api_key,
                    base_url=base_url,
                    model=model,
                    image_path=find_conditioning_image(image_name, images_dir)
                    if image_name
                    else None,
                )
            )
        except Exception as e:  # noqa: BLE001 - recorded per clip; the rest still run
            logger.warning(f"Could not judge {entry['file']}: {e}")
            record["error"] = str(e)
        clips.append(record)
    judged = [clip["overall"] for clip in clips if "overall" in clip]
    return {
        "model": model,
        "criteria": CRITERIA,
        "mean_overall": round(statistics.mean(judged), 2) if judged else None,
        "num_judged": len(judged),
        "clips": clips,
    }


def to_markdown(result: dict, title: str) -> str:
    lines = [
        f"### Video LLM judge: {title}",
        "",
        f"Model `{result['model']}`; {result['num_judged']}/{len(result['clips'])} "
        f"clips judged; mean overall **{result['mean_overall']}** / 5. "
        "Informational, not gated.",
        "",
        "| Clip | Prompt | "
        + " | ".join(name.replace("_", " ") for name in CRITERIA)
        + " | Overall | Issues |",
        "|" + "---|" * (len(CRITERIA) + 4),
    ]
    for clip in result["clips"]:
        if "error" in clip:
            cells = ["—"] * len(CRITERIA) + ["—", f"not judged: {clip['error'][:80]}"]
        else:
            cells = [str(clip["scores"][name]) for name in CRITERIA] + [
                str(clip["overall"]),
                "; ".join(clip["issues"]) or "none",
            ]
        lines.append(
            f"| {clip['file'][:2]} | {clip['prompt']} | " + " | ".join(cells) + " |"
        )
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(message)s")
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--videos-dir", type=Path, required=True)
    parser.add_argument(
        "--images-dir",
        type=Path,
        help="default: whichever test_fixtures/datasets pair set has each image",
    )
    parser.add_argument("--out", type=Path, help="default: <videos-dir>/llm_judge.json")
    parser.add_argument("--summary-md", type=Path, help="append a markdown table here")
    args = parser.parse_args(argv)

    api_key, base_url = os.getenv("TT_CHAT_API_KEY"), os.getenv("TT_CHAT_URL")
    if not api_key or not base_url:
        print("Video LLM judge skipped: TT_CHAT_API_KEY and TT_CHAT_URL are not set.")
        return 0
    result = judge_directory(
        args.videos_dir,
        api_key=api_key,
        base_url=base_url,
        model=os.getenv("TT_CHAT_MODEL") or DEFAULT_MODEL,
        images_dir=args.images_dir,
    )
    out = args.out or args.videos_dir / "llm_judge.json"
    out.write_text(json.dumps(result, indent=2) + "\n")
    markdown = to_markdown(result, args.videos_dir.parent.parent.name)
    print(markdown)
    if args.summary_md:
        with open(args.summary_md, "a") as f:
            f.write(markdown + "\n")
    # Judged nothing at all (e.g. the gateway refused images): say so in the step.
    return 0 if result["num_judged"] else 1


if __name__ == "__main__":
    sys.exit(main())
